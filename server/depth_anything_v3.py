import os
import cv2
import torch
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image
from transformers import pipeline
from sklearn.linear_model import RANSACRegressor

# 1. Initialize Depth Estimation Pipeline
device = 0 if torch.cuda.is_available() else -1
pipe = pipeline(
    task="depth-estimation",
    model="depth-anything/Depth-Anything-V2-Base-hf",
    device=device
)

def detrend_border_plane(depth_map, border_width_ratio=0.10):
    """
    Fits a 2D baseline plane using ONLY border pixels (surrounding road surface)
    and subtracts it to isolate true cavity depth.
    """
    h, w = depth_map.shape
    border_w = max(2, int(w * border_width_ratio))
    border_h = max(2, int(h * border_width_ratio))

    # Generate mask for border pixels
    border_mask = np.zeros((h, w), dtype=bool)
    border_mask[:border_h, :] = True
    border_mask[-border_h:, :] = True
    border_mask[:, :border_w] = True
    border_mask[:, -border_w:] = True

    y_coords, x_coords = np.where(border_mask)
    z_values = depth_map[y_coords, x_coords]

    # Fit 2D plane via RANSAC
    X = np.column_stack((x_coords, y_coords))
    ransac = RANSACRegressor(residual_threshold=1.5, random_state=42)
    ransac.fit(X, z_values)

    # Predict ground plane across the entire crop matrix
    grid_y, grid_x = np.indices((h, w))
    full_grid = np.column_stack((grid_x.ravel(), grid_y.ravel()))
    baseline_plane = ransac.predict(full_grid).reshape(h, w)

    # Depth Anything V2 yields larger values closer to camera.
    # Road surface (baseline) is closer than the pothole pit (cavity).
    relative_cavity = baseline_plane - depth_map
    relative_cavity = np.maximum(0, relative_cavity)  # Retain cavity depths only

    return relative_cavity, baseline_plane

def analyze_pothole_crop(img_path, output_folder, upscale_factor=2):
    filename = os.path.basename(img_path)

    # Load and upscale image to sharpen micro-relief features
    raw_image = Image.open(img_path).convert("RGB")
    w, h = raw_image.size
    if upscale_factor > 1:
        raw_image = raw_image.resize((w * upscale_factor, h * upscale_factor), Image.LANCZOS)

    # Estimate raw depth
    result = pipe(raw_image)
    depth_map = np.array(result["depth"]).astype(np.float32)

    # Apply border-anchored detrending
    cavity_depth, baseline_plane = detrend_border_plane(depth_map)

    # Calculate Quantitative Metrics
    max_depth = np.max(cavity_depth)
    mean_depth = np.mean(cavity_depth[cavity_depth > 0]) if np.any(cavity_depth > 0) else 0.0
    lci_score = np.sum(cavity_depth)  # Localized Cavity Index (Volume Score)

    # Extract cross-section profiles through deepest point
    max_y, max_x = np.unravel_index(np.argmax(cavity_depth), cavity_depth.shape)
    x_slice = cavity_depth[max_y, :]
    y_slice = cavity_depth[:, max_x]

    # Generate Output Visualizations
    fig = plt.figure(figsize=(16, 4))

    # Subplot 1: Crop Image
    ax1 = fig.add_subplot(1, 4, 1)
    ax1.imshow(raw_image)
    ax1.set_title("RF-DETR Crop (Upscaled)")
    ax1.axis("off")

    # Subplot 2: Raw Depth Map
    ax2 = fig.add_subplot(1, 4, 2)
    ax2.imshow(depth_map, cmap="turbo")
    ax2.set_title("Raw Model Depth")
    ax2.axis("off")

    # Subplot 3: Detrended Cavity Depth Map
    ax3 = fig.add_subplot(1, 4, 3)
    im3 = ax3.imshow(cavity_depth, cmap="inferno")
    ax3.plot(max_x, max_y, 'cx', markersize=8, markeredgewidth=2)
    ax3.set_title(f"Detrended Cavity (LCI: {lci_score:.1f})")
    ax3.axis("off")
    plt.colorbar(im3, ax=ax3, fraction=0.046, pad=0.04)

    # Subplot 4: Axial Depth Profiles
    ax4 = fig.add_subplot(1, 4, 4)
    ax4.plot(x_slice, label='Horizontal (X)', color='red', linewidth=1.5)
    ax4.plot(y_slice, label='Vertical (Y)', color='cyan', linewidth=1.5)
    ax4.set_title("Depression Profile")
    ax4.set_xlabel("Pixels")
    ax4.set_ylabel("Relative Depth (ΔZ)")
    ax4.legend(fontsize=8)
    ax4.grid(True, linestyle='--', alpha=0.4)

    plt.tight_layout()
    save_path = os.path.join(output_folder, f"detrended_{filename}")
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    plt.close()

    # Save raw array outputs
    np.save(os.path.join(output_folder, f"cavity_array_{os.path.splitext(filename)[0]}.npy"), cavity_depth)

    return {
        "filename": filename,
        "max_depth": max_depth,
        "mean_depth": mean_depth,
        "lci_score": lci_score
    }

