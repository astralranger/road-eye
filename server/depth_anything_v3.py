import numpy as np

def save_pothole_ply(X, Y, Z, output_path="/content/pothole_3d.ply"):
    """Converts (X, Y, Z) coordinates into a PLY Point Cloud file without Open3D."""
    # Flatten and stack coordinates
    points = np.column_stack((X.ravel(), Y.ravel(), Z.ravel()))

    # Filter out NaNs or invalid values
    valid_mask = ~np.isnan(points).any(axis=1)
    points = points[valid_mask]

    # Manually write PLY header and data
    num_points = len(points)
    header = [
        "ply",
        "format ascii 1.0",
        f"element vertex {num_points}",
        "property float x",
        "property float y",
        "property float z",
        "end_header"
    ]

    with open(output_path, "w") as f:
        f.write("\n".join(header) + "\n")
        np.savetxt(f, points, fmt="%.6f %.6f %.6f")

    print(f"Successfully saved {num_points} points to: {output_path}")

