def process_video_frame(video_path, frame_number=0):
    """Extracts a specific frame from the dashcam video."""
    cap = cv2.VideoCapture(video_path)
    cap.set(cv2.CAP_PROP_POS_FRAMES, frame_number)
    ret, frame = cap.read()
    cap.release()
    if not ret:
        raise ValueError(f"Could not read frame {frame_number} from video {video_path}")
    frame_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    return Image.fromarray(frame_rgb)

def generate_3d_gaussian_road_plot(image_pil, downsample_factor=4, gaussian_sigma=2.0):
    """
    Estimates depth, projects to 3D, fits a Gaussian spatial filter,
    and plots an interactive 3D surface mesh using Plotly.
    """
    # 1. Run Depth Anything Model
    raw_w, raw_h = image_pil.size
    result = pipe(image_pil)
    depth_map = np.array(result["depth"]).astype(np.float32)

    # 2. Downsample matrix for fast 3D rendering
    depth_sub = depth_map[::downsample_factor, ::downsample_factor]
    img_sub = np.array(image_pil)[::downsample_factor, ::downsample_factor]
    h, w = depth_sub.shape

    # 3. Apply 3D Gaussian smoothing to reduce sensor/monocular noise
    depth_smoothed = gaussian_filter(depth_sub, sigma=gaussian_sigma)

    # 4. Construct 3D Coordinate Grid (X, Y, Z)
    # Estimate simple intrinsic parameters based on frame dimensions
    fx = fy = max(w, h)
    cx, cy = w / 2.0, h / 2.0

    u = np.arange(w)
    v = np.arange(h)
    u_grid, v_grid = np.meshgrid(u, v)

    # Re-project to 3D Cartesian coordinates
    Z = depth_smoothed
    X = (u_grid - cx) * Z / fx
    Y = -(v_grid - cy) * Z / fy  # Invert Y for correct visual orientation

    # Convert RGB frame into hex colors for 3D point cloud mapping
    colors = [
        f'rgb({img_sub[r, c, 0]},{img_sub[r, c, 1]},{img_sub[r, c, 2]})'
        for r in range(h) for c in range(w)
    ]

    # 5. Render Interactive 3D Surface Plot
    fig = go.Figure(data=[
        go.Surface(
            x=X,
            y=Y,
            z=Z,
            surfacecolor=depth_smoothed,
            colorscale='Turbo',
            colorbar=dict(title='Depth (Z)')
        )
    ])

    fig.update_layout(
        title="Dashcam 3D Gaussian Surface Depth Reconstruction",
        scene=dict(
            xaxis_title="Camera X (m)",
            yaxis_title="Road Distance Y (m)",
            zaxis_title="Elevation Z (m)",
            aspectratio=dict(x=1, y=2, z=0.5),
            camera=dict(eye=dict(x=0, y=-1.5, z=0.8))
        ),
        margin=dict(l=0, r=0, b=0, t=40)
    )

    return fig

