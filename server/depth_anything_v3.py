def generate_3d_splat_from_video(video_path="/content/000.mp4", frame_idx=0, downsample=2):
    if not os.path.exists(video_path):
        raise FileNotFoundError(f"Video file not found at '{video_path}'. Please check your file name and location.")

    print(f"Loading Depth Model & Processing '{video_path}'...")
    device = 0 if torch.cuda.is_available() else -1
    pipe = pipeline(task="depth-estimation", model="depth-anything/Depth-Anything-V2-Base-hf", device=device)

    # 1. Extract Video Frame
    cap = cv2.VideoCapture(video_path)
    cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
    ret, frame_bgr = cap.read()
    cap.release()

    if not ret:
        raise ValueError(f"Could not read frame {frame_idx} from video.")

    frame_rgb = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2RGB)
    raw_pil = Image.fromarray(frame_rgb)

    # 2. Run Monocular Depth Estimation
    result = pipe(raw_pil)
    depth_map = np.array(result["depth"]).astype(np.float32)

    # 3. Downsample for cleaner 3D point density
    depth_sub = depth_map[::downsample, ::downsample]
    rgb_sub = frame_rgb[::downsample, ::downsample]
    h, w = depth_sub.shape

    # 4. Convert 2D Depth to 3D Cartesian Coordinates (X, Y, Z)
    fx = fy = max(w, h)
    cx, cy = w / 2.0, h / 2.0

    u, v = np.meshgrid(np.arange(w), np.arange(h))
    Z = depth_sub
    X = (u - cx) * Z / fx
    Y = -(v - cy) * Z / fy  # Invert Y for correct camera orientation

    # Flatten arrays
    x_pts = X.ravel()
    y_pts = Y.ravel()
    z_pts = Z.ravel()
    r_pts = rgb_sub[:, :, 0].ravel()
    g_pts = rgb_sub[:, :, 1].ravel()
    b_pts = rgb_sub[:, :, 2].ravel()

    valid_mask = ~np.isnan(z_pts)
    x_pts, y_pts, z_pts = x_pts[valid_mask], y_pts[valid_mask], z_pts[valid_mask]
    r_pts, g_pts, b_pts = r_pts[valid_mask], g_pts[valid_mask], b_pts[valid_mask]
    num_pts = len(x_pts)

    # ----------------------------------------------------
    # Export 1: Standard RGB Point Cloud PLY
    # ----------------------------------------------------
    std_ply_path = "/content/000_pointcloud.ply"
    std_header = f"""ply
format ascii 1.0
element vertex {num_pts}
property float x
property float y
property float z
property uchar red
property uchar green
property uchar blue
end_header
"""
    std_data = np.column_stack((x_pts, y_pts, z_pts, r_pts, g_pts, b_pts))
    with open(std_ply_path, "w") as f:
        f.write(std_header)
        np.savetxt(f, std_data, fmt="%.4f %.4f %.4f %d %d %d")
    print(f"Saved: {std_ply_path}")

    # ----------------------------------------------------
    # Export 2: True 3D Gaussian Splat PLY
    # ----------------------------------------------------
    # Convert RGB [0-255] to Spherical Harmonics Zero-Order (f_dc)
    SH_C0 = 0.28209479177387814
    f_dc_0 = ((r_pts / 255.0) - 0.5) / SH_C0
    f_dc_1 = ((g_pts / 255.0) - 0.5) / SH_C0
    f_dc_2 = ((b_pts / 255.0) - 0.5) / SH_C0

    # Define Gaussian parameters (Log scale for size, Logit for opacity)
    scale = np.full(num_pts, -5.5, dtype=np.float32)  # Log scale radius
    opacity = np.full(num_pts, 3.0, dtype=np.float32) # High opacity logit
    rot_0 = np.ones(num_pts, dtype=np.float32)        # Quaternion W
    rot_123 = np.zeros(num_pts, dtype=np.float32)     # Quaternion X, Y, Z
    normals = np.zeros(num_pts, dtype=np.float32)     # Normals

    gs_ply_path = "/content/000_gaussian_splat.ply"
    gs_header = f"""ply
format ascii 1.0
element vertex {num_pts}
property float x
property float y
property float z
property float nx
property float ny
property float nz
property float f_dc_0
property float f_dc_1
property float f_dc_2
property float opacity
property float scale_0
property float scale_1
property float scale_2
property float rot_0
property float rot_1
property float rot_2
property float rot_3
end_header
"""
    gs_data = np.column_stack((
        x_pts, y_pts, z_pts,
        normals, normals, normals,
        f_dc_0, f_dc_1, f_dc_2,
        opacity,
        scale, scale, scale,
        rot_0, rot_123, rot_123, rot_123
    ))

    with open(gs_ply_path, "w") as f:
        f.write(gs_header)
        np.savetxt(f, gs_data, fmt="%.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f")
    print(f"Saved: {gs_ply_path}")

    # Trigger download of Gaussian Splat PLY to local computer
    files.download(gs_ply_path)

